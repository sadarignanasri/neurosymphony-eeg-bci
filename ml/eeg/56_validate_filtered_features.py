# 5. HELPER — FIND CSV FILE
# ============================================================

def find_condition_file(condition):
    """
    Find the Step 55 feature CSV for a given condition.

    Example:
        condition =
        butterworth_alpha_8_13Hz

    Expected:
        step55_butterworth_alpha_8_13Hz.csv

    Timing CSVs are explicitly excluded.
    """

    exact_file = (
        INPUT_DIR /
        f"step55_{condition}.csv"
    )

    if exact_file.exists():
        return exact_file

    # Fallback search
    candidates = list(
        INPUT_DIR.glob(
            f"*{condition}*.csv"
        )
    )

    candidates = [
        path
        for path in candidates
        if "timing" not in path.name.lower()
    ]

    if not candidates:
        raise FileNotFoundError(
            f"\nCould not find feature CSV for:\n"
            f"  {condition}\n\n"
            f"Expected file:\n"
            f"  {exact_file}"
        )

    if len(candidates) > 1:
        print(
            "\nWARNING: Multiple files found for "
            f"{condition}:"
        )

        for path in candidates:
            print(f"  {path}")

        print(
            f"\nUsing:\n  {candidates[0]}"
        )

    return candidates[0]


# ============================================================
# 6. HELPER — IDENTIFY FEATURE COLUMNS
# ============================================================

def identify_feature_columns(df):
    """
    Identify the 320 EEG band-power feature columns.

    Expected format:

        A1_delta_power
        A1_theta_power
        A1_alpha_power
        A1_beta_power
        A1_gamma_power

        ...

        B32_delta_power
        B32_theta_power
        B32_alpha_power
        B32_beta_power
        B32_gamma_power

    Total:

        64 channels × 5 bands = 320 features
    """

    pattern = re.compile(
        r"^(A|B)\d+_"
        r"(delta|theta|alpha|beta|gamma)"
        r"_power$"
    )

    feature_cols = [
        col
        for col in df.columns
        if pattern.match(str(col))
    ]

    return feature_cols


# ============================================================
# 7. HELPER — GET BAND
# ============================================================

def get_band_from_feature(feature):
    """
    Extract frequency band from a feature name.
    """

    match = re.match(
        r"^(A|B)\d+_"
        r"(delta|theta|alpha|beta|gamma)"
        r"_power$",
        str(feature)
    )

    if match:
        return match.group(2)

    return None


# ============================================================
# 8. HELPER — GET CHANNEL
# ============================================================

def get_channel_from_feature(feature):
    """
    Extract EEG channel from a feature name.

    Examples:
        A1_alpha_power -> A1
        B30_beta_power -> B30
    """

    match = re.match(
        r"^(A|B)(\d+)_"
        r"(delta|theta|alpha|beta|gamma)"
        r"_power$",
        str(feature)
    )

    if match:
        return (
            match.group(1)
            + match.group(2)
        )

    return None


# ============================================================
# 9. HELPER — CONDITION TYPE
# ============================================================

def classify_condition(condition):
    """
    Determine whether the condition is:

        broad
        delta
        theta
        alpha
        beta
        gamma
    """

    if "broad_1_45Hz" in condition:
        return "broad"

    if "delta_1_4Hz" in condition:
        return "delta"

    if "theta_4_8Hz" in condition:
        return "theta"

    if "alpha_8_13Hz" in condition:
        return "alpha"

    if "beta_13_30Hz" in condition:
        return "beta"

    if "gamma_30_45Hz" in condition:
        return "gamma"

    return "unknown"


# ============================================================
# 10. HELPER — FILTER METHOD
# ============================================================

def get_method(condition):
    """
    Determine the filtering method.
    """

    if condition.startswith(
        "notch_butterworth"
    ):
        return "notch_butterworth"

    if condition.startswith(
        "notch_fir"
    ):
        return "notch_fir"

    if condition.startswith(
        "butterworth"
    ):
        return "butterworth"

    if condition.startswith("fir"):
        return "fir"

    return "unknown"


# ============================================================
# 11. HELPER — RELEVANT BANDS
# ============================================================

def get_relevant_bands(condition):
    """
    Determine which bands should be interpreted.

    Broad:
        all five bands.

    Narrow:
        only its corresponding band.

    Example:

        butterworth_alpha_8_13Hz
        -> alpha only
    """

    condition_type = classify_condition(
        condition
    )

    if condition_type == "broad":
        return list(BANDS.keys())

    if condition_type in BANDS:
        return [condition_type]

    return []


# ============================================================
# 12. VALIDATE CLASS DISTRIBUTION
# ============================================================

def validate_class_distribution(labels):
    """
    Verify:

        8 classes
        labels 0–7
        90 trials per class
    """

    unique_labels = sorted(
        labels.unique().tolist()
    )

    class_counts = (
        labels
        .value_counts()
        .sort_index()
    )

    labels_correct = (
        unique_labels == EXPECTED_LABELS
    )

    counts_correct = all(
        class_counts.get(label, 0) == 90
        for label in EXPECTED_LABELS
    )

    return (
        labels_correct
        and counts_correct
    ), unique_labels, class_counts


